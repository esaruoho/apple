#!/usr/bin/env python3
"""Generate wiki/INDEX.md from a filesystem walk.

Karpathy-style content-oriented index: one line per page, grep-friendly,
grouped by category. Source of truth is the filesystem; the index is
re-derived on every run.

For each .md page under wiki/:
- Title: H1 line ("# X") OR YAML frontmatter `name:` field
- Summary: YAML frontmatter `description:` field OR first non-heading paragraph
- Path: relative to wiki/

Categories are top-level subdirs. README.md and INDEX.md (this output) are excluded.

Usage:
    python3 bin/wiki-index.py            # write wiki/INDEX.md
    python3 bin/wiki-index.py --stdout   # print to stdout
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
WIKI = ROOT / "wiki"

CATEGORY_ORDER = ["entities", "concepts", "lessons", "operations", "compiled"]
CATEGORY_TAGLINE = {
    "entities":   "one page per thing — person, app, device, package",
    "concepts":   "how X works — atlases, principles, patterns",
    "lessons":    "didactic / narrative — runbooks and curriculum",
    "operations": "active project state — current work, status, plans",
    "compiled":   "auto-generated, do not hand-edit",
}

FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.S)
H1 = re.compile(r"(?m)^# (.+)$")


def yaml_lite(block: str) -> dict:
    """Tiny YAML parser — top-level key: value only, single-line values."""
    out = {}
    for line in block.splitlines():
        m = re.match(r"^([a-zA-Z_][a-zA-Z0-9_-]*):\s*(.*)$", line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            # Strip surrounding quotes
            if (val.startswith('"') and val.endswith('"')) or (val.startswith("'") and val.endswith("'")):
                val = val[1:-1]
            out[key] = val
    return out


def first_paragraph(body: str) -> str:
    """First non-heading, non-blank paragraph; collapse to one line; ~120 chars."""
    paras = re.split(r"\n\s*\n", body.strip())
    for p in paras:
        p = p.strip()
        if not p or p.startswith("#") or p.startswith(">") or p.startswith("|") or p.startswith("- "):
            continue
        # Single-line, strip markdown
        line = re.sub(r"\s+", " ", p)
        line = re.sub(r"\*\*([^*]+)\*\*", r"\1", line)
        line = re.sub(r"\*([^*]+)\*", r"\1", line)
        line = re.sub(r"`([^`]+)`", r"\1", line)
        line = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", line)
        if len(line) > 120:
            line = line[:117].rstrip() + "..."
        return line
    return ""


def extract(path: pathlib.Path) -> tuple[str, str]:
    text = path.read_text()
    fm = FRONTMATTER.match(text)
    meta = {}
    body = text
    if fm:
        meta = yaml_lite(fm.group(1))
        body = text[fm.end():]
    # Title
    h1 = H1.search(body)
    title = (h1.group(1).strip() if h1 else meta.get("name", path.stem))
    # Description
    desc = meta.get("description") or first_paragraph(body) or ""
    return title, desc


def main():
    pages_by_cat: dict[str, list[tuple[str, str, str]]] = {c: [] for c in CATEGORY_ORDER}
    extras: dict[str, list[tuple[str, str, str]]] = {}

    for path in sorted(WIKI.rglob("*.md")):
        rel = path.relative_to(WIKI)
        if rel.name in {"INDEX.md", "README.md", "log.md"}:
            continue
        parts = rel.parts
        if len(parts) < 2:
            continue  # top-level files (none expected)
        cat = parts[0]
        title, desc = extract(path)
        entry = (str(rel), title, desc)
        if cat in pages_by_cat:
            pages_by_cat[cat].append(entry)
        else:
            extras.setdefault(cat, []).append(entry)

    lines = [
        "# Wiki Index",
        "",
        "*Auto-generated by `bin/wiki-index.py`. Do not hand-edit — your changes will be overwritten.*",
        "",
        f"{sum(len(v) for v in pages_by_cat.values()) + sum(len(v) for v in extras.values())} pages across {len([c for c in pages_by_cat if pages_by_cat[c]]) + len(extras)} categories.",
        "",
    ]

    for cat in CATEGORY_ORDER:
        entries = pages_by_cat[cat]
        if not entries:
            continue
        tagline = CATEGORY_TAGLINE.get(cat, "")
        lines.append(f"## `{cat}/` — {tagline}" if tagline else f"## `{cat}/`")
        lines.append("")
        for rel, title, desc in entries:
            if desc:
                lines.append(f"- `{rel}` — **{title}** — {desc}")
            else:
                lines.append(f"- `{rel}` — **{title}**")
        lines.append("")

    for cat in sorted(extras):
        lines.append(f"## `{cat}/`")
        lines.append("")
        for rel, title, desc in extras[cat]:
            if desc:
                lines.append(f"- `{rel}` — **{title}** — {desc}")
            else:
                lines.append(f"- `{rel}` — **{title}**")
        lines.append("")

    output = "\n".join(lines).rstrip() + "\n"
    if "--stdout" in sys.argv:
        sys.stdout.write(output)
    else:
        out_path = WIKI / "INDEX.md"
        out_path.write_text(output)
        n = output.count("\n- ")
        print(f"wrote {out_path} ({n} entries, {len(output.splitlines())} lines)")


if __name__ == "__main__":
    main()
