#!/usr/bin/env python3
"""gen-features-index.py — regenerate features/INDEX.md, the AppleBar feature index.

AUTO-GENERATED output. Never hand-write features/INDEX.md — it is consolidated, on
every commit (via hooks/pre-commit), from two sources:
  1. shared/intents.json  → the capability catalog (every action you can type)
  2. features/*.feature    → the behaviour cards, parsed by Convey itself
     (`convey read`), so the report-card tooling is the single parser. This is the
     "use Convey to its fullest" path: the cards are the source, Convey reads them.

Apple-native: Python 3 stdlib + the in-repo `convey`. Re-run safe (same in → same out).
"""
import json
import glob
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
os.chdir(ROOT)


def caps_table() -> str:
    try:
        cat = json.load(open("shared/intents.json"))["intents"]
    except Exception as e:
        return f"_(couldn't read shared/intents.json: {e})_\n"
    rows = ["| action | needs arg | what it does |", "|---|---|---|"]
    for c in cat:
        rows.append(f"| `{c['action']}` | {'yes' if c.get('needsArg') else '—'} | {c.get('desc', '')} |")
    head = f"## Capabilities — {len(cat)} actions (`shared/intents.json` → `bin/apple-do`)\n\n"
    return head + "\n".join(rows) + "\n"


def cards_section() -> str:
    files = sorted(glob.glob("features/*.feature"))
    if not files:
        return "_(no feature cards found)_\n"
    try:
        r = subprocess.run(["./bin/convey", "read", *files],
                           capture_output=True, text=True, timeout=90)
        body = (r.stdout or "").strip() or "(convey read produced no output)"
    except Exception as e:
        body = f"(convey read failed: {e})"
    return "## Behaviour cards — graded Gherkin (parsed by `convey read features/*.feature`)\n\n```\n" + body + "\n```\n"


doc = [
    "# AppleBar — feature index",
    "",
    "> AUTO-GENERATED by `bin/gen-features-index.py` on every commit (pre-commit hook).",
    "> **Do not edit.** Change a `features/*.feature` card or `shared/intents.json`,",
    "> then commit — this file reconsolidates itself.",
    "",
    "Two parts: the **capability catalog** (what you can type) and the **behaviour cards**",
    "(graded Given/When/Then, consolidated straight from the cards by Convey).",
    "",
    caps_table(),
    "Plus LLM prefixes: `? <q>` (grounded in your learned rules), `chat <q>` / "
    "`converse <q>` (general on-device LLM on the Mini).",
    "",
    cards_section(),
]
with open("features/INDEX.md", "w") as f:
    f.write("\n".join(doc) + "\n")
print("features/INDEX.md regenerated")
